// node scripts/inertia.mjs -> src/robot/inertia.ts: each link's mass (kg) and centre of mass (m, link frame) for G1 and GO2, taken from
// the physics models public/physics/<robot>/scene.xml (Unitree's MuJoCo models: their bodies are the URDF links, fixed links fused
// into their parent; GO2's root body base_link is the URDF base). 검수 목록 발 미끄러짐·마찰 부족 (수정변동사항.md §16) use it for the
// whole-body centre of mass. Rerun after a physics model changes.
import { readFileSync, writeFileSync } from 'node:fs'
const attr = (s, k) => (s.match(new RegExp(`\\b${k}="([^"]*)"`)) ?? [])[1]
function inertia(r) {
  const xml = readFileSync(`public/physics/${r}/scene.xml`, 'utf8'), model = JSON.parse(readFileSync(`public/robots/${r}/model.json`, 'utf8'))
  const children = new Set(model.joints.map(j => j.child)), rootLink = Object.keys(model.links).find(n => !children.has(n))
  const stack = [], links = {}
  for (const [, close, tag, a, self] of xml.matchAll(/<(\/?)(body|inertial)\b([^>]*?)(\/?)>/g)) {
    if (tag === 'body') {
      if (close) { stack.pop(); continue }
      const name = attr(a, 'name')
      stack.push(!stack.length && !model.links[name] ? rootLink : name) // the top body is the root link
      if (self) stack.pop()
    } else if (!close) {
      const name = stack.at(-1)
      if (!model.links[name]) throw new Error(`${r}: body ${name} is not a link of public/robots/${r}/model.json`)
      links[name] = [+attr(a, 'mass'), ...(attr(a, 'pos') ?? '0 0 0').split(/\s+/).map(Number)].map(v => +v.toPrecision(7))
    }
  }
  return links
}
const data = { g1: inertia('g1'), go2: inertia('go2') }
const total = l => Object.values(l).reduce((s, x) => s + x[0], 0).toFixed(3)
writeFileSync('src/robot/inertia.ts', `// Generated by scripts/inertia.mjs from public/physics/<robot>/scene.xml — do not edit by hand.
// Link → [mass kg, centre of mass x, y, z m in the link frame]. G1 ${total(data.g1)} kg, GO2 ${total(data.go2)} kg.
import type { RobotKind } from './types'
export const INERTIA: Record<RobotKind, Record<string, [number, number, number, number]>> = ${JSON.stringify(data)}
`)
console.log('G1', total(data.g1), 'kg ·', Object.keys(data.g1).length, 'links | GO2', total(data.go2), 'kg ·', Object.keys(data.go2).length, 'links')
